#!/usr/bin/env python3
"""Draws the app icon: a round lens whose shutter is six flat triangular blades.

Writes the adaptive icon's vector layers into the Android app's res/ folder
and, with --svg DIR, the same shapes as SVG for a preview:

    python3 tools/app-icon/make-icon.py [--svg DIR]

The geometry lives on the adaptive icon's 108 x 108 canvas, centred at
(54, 54), inside the 33-unit safe-zone radius, so no launcher mask cuts it.
Flat colours, no gradients or shadows, as in the system icons.

  - the ring: a smooth dark annulus;
  - the shutter: six triangular blades in a pinwheel around a hexagonal
    aperture. Each side of the hexagon, extended, reaches the ring; blade i
    is the triangle between two consecutive extended sides, one flat colour
    each, lit from the top left like the Tessels of a Mosaic.

The monochrome layer (themed icons) keeps the ring and the blades in one
colour, the blades pulled apart by a thin gap so they still read.
"""

import math
import os
import sys

C = 54.0              # canvas centre
RING_OUT = 31.0       # the ring's outer radius (safe zone: 33)
RING_IN = 25.5        # its inner radius, where the blades end
APERTURE = 9.5        # the aperture hexagon's circumradius
GAP = 0.7             # the monochrome blades' gap

BACKGROUND = "#E6F4EA"
RING = "#3C4043"
BARREL = "#202124"    # behind the blades, and the aperture
# The blades, from the most lit to the most shaded.
TONES = ["#A7F3EC", "#5EDBD0", "#1FB8A9", "#12968A", "#0B6E66", "#064C46"]
LIGHT_DEGREES = -125  # where the light comes from: the top left (y grows downwards)

RES = os.path.join(os.path.dirname(__file__), "..", "..", "android", "app", "src", "main", "res")


def polar(r, degrees):
    a = math.radians(degrees)
    return (C + r * math.cos(a), C + r * math.sin(a))


def exit_point(p, q, r):
    """Where the ray from p through q leaves the circle of radius r around the centre."""
    dx, dy = q[0] - p[0], q[1] - p[1]
    fx, fy = p[0] - C, p[1] - C
    a = dx * dx + dy * dy
    b = 2 * (fx * dx + fy * dy)
    c = fx * fx + fy * fy - r * r
    t = (-b + math.sqrt(b * b - 4 * a * c)) / (2 * a)
    return (p[0] + t * dx, p[1] + t * dy)


def shutter():
    """The aperture hexagon and the six blades, most lit first."""
    h = [polar(APERTURE, 60 * i - 90) for i in range(6)]
    q = [exit_point(h[i], h[(i + 1) % 6], RING_IN) for i in range(6)]
    blades = [(h[(i + 1) % 6], q[i], q[(i + 1) % 6]) for i in range(6)]

    def lit(blade):
        x = sum(p[0] for p in blade) / 3 - C
        y = sum(p[1] for p in blade) / 3 - C
        return math.cos(math.atan2(y, x) - math.radians(LIGHT_DEGREES))

    return h, sorted(blades, key=lambda b: -lit(b))


def inset(triangle, gap):
    """The triangle shrunk so each edge moves [gap] inwards (its incircle's centre fixed)."""
    (ax, ay), (bx, by), (cx, cy) = triangle
    la, lb, lc = math.dist((bx, by), (cx, cy)), math.dist((ax, ay), (cx, cy)), math.dist((ax, ay), (bx, by))
    s = la + lb + lc
    ix, iy = (la * ax + lb * bx + lc * cx) / s, (la * ay + lb * by + lc * cy) / s
    area = abs((bx - ax) * (cy - ay) - (cx - ax) * (by - ay)) / 2
    k = max(0.0, 1 - gap * s / (2 * area))
    return [(ix + k * (x - ix), iy + k * (y - iy)) for x, y in triangle]


def path(points):
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points) + " Z"


def circle(r):
    """A circle as a path: two arcs."""
    return f"M{C - r:.2f},{C:.2f} A{r:.2f},{r:.2f} 0 1,1 {C + r:.2f},{C:.2f} A{r:.2f},{r:.2f} 0 1,1 {C - r:.2f},{C:.2f} Z"


def colour_layer():
    hexagon, blades = shutter()
    shapes = [
        (circle(RING_OUT) + " " + circle(RING_IN), RING, True),
        (circle(RING_IN + 0.05), BARREL, False),
    ]
    shapes += [(path(b), tone, False) for b, tone in zip(blades, TONES)]
    shapes.append((path(hexagon), BARREL, False))
    return shapes


def monochrome_layer():
    _, blades = shutter()
    shapes = [(circle(RING_OUT) + " " + circle(RING_IN), "#FFFFFF", True)]
    shapes += [(path(inset(b, GAP)), "#FFFFFF", False) for b in blades]
    return shapes


def vector(shapes):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/app-icon/make-icon.py: edit the script, not this file. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
    ]
    for d, colour, evenodd in shapes:
        rule = '\n        android:fillType="evenOdd"' if evenodd else ""
        out.append(f'    <path android:fillColor="{colour}"{rule}\n        android:pathData="{d}" />')
    out.append("</vector>")
    return "\n".join(out) + "\n"


def svg(shapes, background):
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="432" height="432" viewBox="0 0 108 108">',
        f'<rect width="108" height="108" fill="{background}"/>',
    ]
    for d, colour, evenodd in shapes:
        rule = ' fill-rule="evenodd"' if evenodd else ""
        out.append(f'<path d="{d}" fill="{colour}"{rule}/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def background_colour():
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/app-icon/make-icon.py: edit the script, not this file. -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">{BACKGROUND}</color>\n'
        "</resources>\n"
    )


def main():
    drawable = os.path.join(RES, "drawable")
    os.makedirs(drawable, exist_ok=True)
    with open(os.path.join(drawable, "ic_launcher_foreground.xml"), "w") as f:
        f.write(vector(colour_layer()))
    with open(os.path.join(drawable, "ic_launcher_monochrome.xml"), "w") as f:
        f.write(vector(monochrome_layer()))
    with open(os.path.join(RES, "values", "ic_launcher_background.xml"), "w") as f:
        f.write(background_colour())
    if "--svg" in sys.argv:
        out = sys.argv[sys.argv.index("--svg") + 1]
        os.makedirs(out, exist_ok=True)
        with open(os.path.join(out, "icon.svg"), "w") as f:
            f.write(svg(colour_layer(), BACKGROUND))
        with open(os.path.join(out, "mono.svg"), "w") as f:
            f.write(svg(monochrome_layer(), "#1F2A37"))


if __name__ == "__main__":
    main()
