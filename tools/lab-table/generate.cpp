// Generates src/mosaic/core/AdaptiveLabTable.inc, the table behind the
// core's exact port of OpenCV's float sRGB -> Lab (cv::COLOR_RGB2Lab).
//
// OpenCV doesn't evaluate the Lab formula for sRGB floats: it interpolates
// a 33x33x33 table of Lab values in 1/2^14 steps, built once in software
// floating point (softfloat), so it is the same on every platform
// (modules/imgproc/src/color_lab.cpp, RGB2Lab_f and initLUTforLABLUVs16).
// Each table entry is OpenCV's Lab of a grid colour (r, g, b) / 32, where
// the interpolation has zero weight on the other corners. So this program
// converts the 33^3 grid colours with cv::cvtColor and recovers the
// integers, checking that each one gives back OpenCV's floats exactly.
//
// Build and run from the repository root:
//   g++ -O2 -std=c++17 tools/lab-table/generate.cpp $(pkg-config --cflags --libs opencv4) -o /tmp/lab-table
//   /tmp/lab-table > src/mosaic/core/AdaptiveLabTable.inc
// The openFrameworks tests check the port against cv::cvtColor on all 2^24
// colours.

#include <opencv2/core.hpp>
#include <opencv2/imgproc.hpp>

#include <cmath>
#include <cstdio>
#include <cstring>

int main() {
    const int dim = 33;
    cv::Mat grid(1, dim * dim * dim, CV_32FC3), lab;
    for (int b = 0; b < dim; b++) {
        for (int g = 0; g < dim; g++) {
            for (int r = 0; r < dim; r++) {
                grid.at<cv::Vec3f>(0, (b * dim + g) * dim + r) = cv::Vec3f(r / 32.f, g / 32.f, b / 32.f);
            }
        }
    }
    cv::cvtColor(grid, lab, cv::COLOR_RGB2Lab);

    auto same = [](float x, float y) { return std::memcmp(&x, &y, sizeof x) == 0; };
    std::printf("// Generated by tools/lab-table/generate.cpp from OpenCV %s: do not edit.\n", CV_VERSION);
    std::printf("// OpenCV's RGB2Lab table (Apache-2.0): L, a, b of grid colour (r, g, b) / 32\n");
    std::printf("// at index ((b * 33 + g) * 33 + r) * 3, in units of 1/2^14 of L / 100 and\n");
    std::printf("// of (a + 128) / 256, (b + 128) / 256.\n");
    for (int i = 0; i < dim * dim * dim; i++) {
        const cv::Vec3f v = lab.at<cv::Vec3f>(0, i);
        const int iL = int(std::lround(v[0] / 100.0 * 16384));
        const int ia = int(std::lround((v[1] + 128.0) / 256.0 * 16384));
        const int ib = int(std::lround((v[2] + 128.0) / 256.0 * 16384));
        // The core's float steps, which must give back OpenCV's values.
        const float L = iL * 1.0f / 16384, a = ia * 1.0f / 16384, b = ib * 1.0f / 16384;
        if (!same(L * 100.0f, v[0]) || !same(a * 256.0f - 128.0f, v[1]) || !same(b * 256.0f - 128.0f, v[2])
            || iL < 0 || iL > 32767 || ia < 0 || ia > 32767 || ib < 0 || ib > 32767) {
            std::fprintf(stderr, "entry %d does not round-trip\n", i);
            return 1;
        }
        std::printf("%d,%d,%d,%s", iL, ia, ib, i % 6 == 5 ? "\n" : "");
    }
    std::printf("\n");
    return 0;
}
